export function isDistinctive(word: string): boolean {
  const normalized = word.toLowerCase().replace(/[^\p{L}\p{N}'-]/gu, '');
  if (normalized.length < 3) return false;
  return !STOPWORDS.has(normalized) && !COMMON_WORDS.has(normalized);
}

export function containsEmotionWord(text: string): boolean {
  return text
    .toLowerCase()
    .split(/[^\p{L}']+/u)
    .some((word) => EMOTION_WORDS.has(word));
}
